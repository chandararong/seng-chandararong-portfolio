/* =========================================================
   SCROLL REVEAL
========================================================= */

const revealObserver =
    new IntersectionObserver(
        entries => {

            entries.forEach(entry => {

                if (
                    entry.isIntersecting
                ) {

                    entry.target.classList.add(
                        "visible"
                    );

                    revealObserver.unobserve(
                        entry.target
                    );

                }

            });

        },
        {
            threshold: 0.12
        }
    );


function observeReveals() {

    document
        .querySelectorAll(
            ".reveal:not(.visible)"
        )
        .forEach(element => {

            revealObserver.observe(
                element
            );

        });

}


/* =========================================================
   SKILL BAR ANIMATION
========================================================= */

const skillObserver =
    new IntersectionObserver(
        entries => {

            entries.forEach(entry => {

                if (
                    entry.isIntersecting
                ) {

                    const bar =
                        entry.target;

                    const width =
                        bar.dataset.width;

                    bar.style.width =
                        width;

                    skillObserver.unobserve(
                        bar
                    );

                }

            });

        },
        {
            threshold: 0.5
        }
    );


function observeSkillBars() {

    document
        .querySelectorAll(
            ".skill-progress"
        )
        .forEach(bar => {

            skillObserver.observe(
                bar
            );

        });

}


