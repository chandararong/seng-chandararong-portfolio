/* =========================================================
   GET UNIQUE CATEGORIES
========================================================= */

function getCategories(data) {

    return [
        "All",
        ...new Set(
            data.map(item => item.category)
        )
    ];

}


/* =========================================================
   RENDER FILTERS
========================================================= */

function renderFilters(
    container,
    data,
    callback
) {

    container.innerHTML = "";

    getCategories(data)
        .forEach((category, index) => {

            const button =
                document.createElement("button");

            button.className =
                `filter-btn ${
                    index === 0
                        ? "active"
                        : ""
                }`;

            button.textContent =
                category;

            button.addEventListener(
                "click",
                () => {

                    container
                        .querySelectorAll(
                            ".filter-btn"
                        )
                        .forEach(btn =>
                            btn.classList.remove(
                                "active"
                            )
                        );

                    button.classList.add(
                        "active"
                    );

                    callback(category);

                }
            );

            container.appendChild(
                button
            );

        });

}


