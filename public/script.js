const lightbox =
    document.getElementById("lightbox");

const lightboxImage =
    document.getElementById(
        "lightboxImage"
    );

const lightboxTitle =
    document.getElementById(
        "lightboxTitle"
    );

const lightboxCategory =
    document.getElementById(
        "lightboxCategory"
    );

const lightboxDescription =
    document.getElementById(
        "lightboxDescription"
    );

const lightboxMeta =
    document.getElementById(
        "lightboxMeta"
    );

const lightboxClose =
    document.getElementById(
        "lightboxClose"
    );

const lightboxPrev =
    document.getElementById(
        "lightboxPrev"
    );

const lightboxNext =
    document.getElementById(
        "lightboxNext"
    );


let currentLightboxItems = [];

let currentLightboxIndex = 0;


function openLightbox(
    items,
    index
) {

    currentLightboxItems =
        items;

    currentLightboxIndex =
        index;

    updateLightbox();

    lightbox.classList.add(
        "active"
    );

    document.body.classList.add(
        "no-scroll"
    );

}


function updateLightbox() {

    const project =
        currentLightboxItems[
            currentLightboxIndex
            ];

    if (!project) return;

    lightboxImage.src =
        project.image;

    lightboxImage.alt =
        project.title;

    lightboxTitle.textContent =
        project.title;

    lightboxCategory.textContent =
        project.category;

    lightboxDescription.textContent =
        project.description || "";

    lightboxMeta.textContent =
        [
            project.date,
            project.client
        ]
            .filter(Boolean)
            .join(" • ");

}


function closeLightbox() {

    lightbox.classList.remove(
        "active"
    );

    document.body.classList.remove(
        "no-scroll"
    );

}


function nextLightbox() {

    currentLightboxIndex =
        (
            currentLightboxIndex + 1
        ) %
        currentLightboxItems.length;

    updateLightbox();

}


function previousLightbox() {

    currentLightboxIndex =
        (
            currentLightboxIndex -
            1 +
            currentLightboxItems.length
        ) %
        currentLightboxItems.length;

    updateLightbox();

}


lightboxClose.addEventListener(
    "click",
    closeLightbox
);

lightboxNext.addEventListener(
    "click",
    nextLightbox
);

lightboxPrev.addEventListener(
    "click",
    previousLightbox
);


lightbox.addEventListener(
    "click",
    event => {

        if (
            event.target ===
            lightbox
        ) {

            closeLightbox();

        }

    }
);


/* =========================================================
   VIDEO MODAL
========================================================= */

const videoModal =
    document.getElementById(
        "videoModal"
    );

const videoPlayer =
    document.getElementById(
        "videoPlayer"
    );

const videoTitle =
    document.getElementById(
        "videoTitle"
    );

const videoCategory =
    document.getElementById(
        "videoCategory"
    );

const videoDescription =
    document.getElementById(
        "videoDescription"
    );

const videoMeta =
    document.getElementById(
        "videoMeta"
    );

const videoClose =
    document.getElementById(
        "videoClose"
    );


function openVideoModal(project) {

    videoPlayer.innerHTML = "";


    if (project.type === "local") {

        const video =
            document.createElement(
                "video"
            );

        video.src =
            project.source;

        video.controls = true;

        video.autoplay = true;

        video.preload = "metadata";

        videoPlayer.appendChild(
            video
        );

    }


    else if (
        project.type === "youtube" ||
        project.type === "vimeo"
    ) {

        const iframe =
            document.createElement(
                "iframe"
            );

        iframe.src =
            project.source;

        iframe.allow =
            "autoplay; fullscreen; picture-in-picture";

        iframe.allowFullscreen =
            true;

        videoPlayer.appendChild(
            iframe
        );

    }


    videoCategory.textContent =
        project.category;

    videoTitle.textContent =
        project.title;

    videoDescription.textContent =
        project.description;

    videoMeta.textContent =
        `${project.year} • ${project.client} • ${project.duration}`;


    videoModal.classList.add(
        "active"
    );

    document.body.classList.add(
        "no-scroll"
    );

}


function closeVideoModal() {

    const video =
        videoPlayer.querySelector(
            "video"
        );

    if (video) {

        video.pause();

        video.currentTime = 0;

    }

    videoPlayer.innerHTML = "";

    videoModal.classList.remove(
        "active"
    );

    document.body.classList.remove(
        "no-scroll"
    );

}


videoClose.addEventListener(
    "click",
    closeVideoModal
);


videoModal.addEventListener(
    "click",
    event => {

        if (
            event.target ===
            videoModal
        ) {

            closeVideoModal();

        }

    }
);


